/* ============================================================================
 *  S3 — 输入捕获：让 STM32 反过来"测量"自己产生的波形
 * ============================================================================
 *  文件：firmware/study/S3_INPUT_CAPTURE/capture.c
 *
 *  为什么要做这个：
 *    前几个 Lab 我们一直在"产生"波形，然后靠示波器肉眼比对。
 *    这个模块换个方向：用 STM32 的**输入捕获**把信号"量"出来 ——
 *    ★ 用你自己产生的 250kHz 波形去喂给自己，看测出来是不是 250kHz。
 *    这形成一个闭环：产生 → 测量 → 验证。也是以后调试任何时序的通用手段。
 *
 *  ---------------------------------------------------------------------------
 *  【原理】
 *    输入捕获 = "边沿到来时，把 CNT 的当前值锁存进 CCRx"
 *
 *        信号 ───╱‾‾‾‾‾╲_____╱‾‾‾‾‾╲_____
 *                 ↑          ↑
 *               捕获1       捕获2
 *               CNT=t1      CNT=t2
 *
 *        周期 = (t2 − t1) 个 tick   （注意计数器回绕，要取模）
 *        频率 = f_cnt / 周期(tick)
 *
 *    本实验：f_cnt = 72MHz，理论周期 = 288 tick → 250kHz
 *
 *  ---------------------------------------------------------------------------
 *  【接线】
 *    PA1（TIM2_CH2，我们产生的 OE 波形）  ──杜邦线──▶  PA6（TIM3_CH1，捕获输入）
 *    （另接 GND 共地；示波器可同时看 PA1 和 PA6 对比）
 *
 *  ===== 任务 =====
 *  T1：用 TIM2_CH2 (PA1) 产生 250kHz、50% 占空比（复用 Lab2 的知识）
 *        PSC=0, ARR=287, CCR2=144，PWM 模式 1，开 CC2E
 *  T2：用 TIM3_CH1 (PA6) 做输入捕获
 *        CCMR1 CC1S = 01（输入，IC1 映射到 TI1）
 *        CCER  CC1E = 1，CC1P = 0（上升沿捕获）
 *        DIER  CC1IE = 1（捕获中断）
 *        开 NVIC
 *  T3：在 ISR 里取两次上升沿的 CNT 差，算出周期/频率
 *  T4：主循环里判断"测到的周期是否 ≈288"，是则点亮 PC13 的 LED
 *        —— 这是你的"自动验收测试"：线接对、参数对，灯就亮
 *
 *  ===== 进阶（做完上面再做）=====
 *  A) 改成"PWM 输入模式"：一次同时测出**周期 + 占空比**
 *     （把 TI1 同时接到 IC1 与 IC2，一个测周期一个测高电平宽度）
 *  B) 用 TIM2 改频率（改 ARR），看 LED 是否还能正确判定
 *  C) 去测一个"外部"信号（比如学长板子上的某个方波），验证通用性
 *
 *  ===== 涉及寄存器 =====
 *    TIM3->CCMR1    CC1S[1:0]（00=输出, 01=输入IC1←TI1, 10=输入IC1←TI2, 11=输入IC1←TRC）
 *                   IC1PSC[3:2] 预分频；IC1F[7:4] 输入滤波
 *    TIM3->CCER     CC1E(0) 捕获使能；CC1P(1) 极性（0=上升沿）
 *    TIM3->DIER     CC1IE(1) 捕获中断；UIE(0) 更新中断（用于记回绕次数）
 *    TIM3->SR       CC1IF(1) 捕获标志；UIF(0) 更新标志
 *    TIM3->CCR1     锁存到的 CNT 值（**只读**）
 *
 *  ===== 思考题 =====
 *  Q1：为什么要处理"计数器回绕"？不处理会怎样？
 *  Q2：输入滤波器 IC1F 有什么用？测 250kHz 时该开多大？
 *  Q3：如果待测信号比 f_cnt 还快，会发生什么？（测量的下限/上限在哪）
 *  Q4：用"测周期"和"在固定时间内数脉冲个数"两种方法，各适合什么频段？
 * ========================================================================== */

