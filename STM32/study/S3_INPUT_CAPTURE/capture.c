int main(void)
{
    /* LED（PC13）配成通用推挽输出 */
    RCC->APB2ENR |= (1U << 4);                              /* GPIOC */
    GPIOC->CRH &= ~(0xFU << ((LED_PIN - 8) * 4));
    GPIOC->CRH |=  (0x3U << ((LED_PIN - 8) * 4));
    GPIOC->BSRR = (1U << LED_PIN);                          /* 先灭（低电平点亮）*/

    wave_gen_init();
    capture_init();

    while (1)
    {
        /* TODO T4：判断测到的周期是否 ≈ 288 tick（±3 的容差） */
        if (g_period_tick >= 285U && g_period_tick <= 291U)
        {
            GPIOC->BRR = (1U << LED_PIN);       /* 点亮：测到 250kHz */
        }
        else
        {
            GPIOC->BSRR = (1U << LED_PIN);      /* 熄灭：没测到/接错线 */
        }
    }
}

