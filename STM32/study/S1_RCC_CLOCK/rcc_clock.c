/* ---------------------------------------------------------------------------
 *  TIM2 更新中断：翻转 PC13
 * ------------------------------------------------------------------------- */
void TIM2_IRQHandler(void)
{
    /* 你的代码：判断 UIF → 翻转 PC13 → 清标志 */
        if (TIM2->SR & (1U << 0)) //检查更新中断标志位
        {
            TIM2->SR &= ~(1U << 0); //清除标志位
            GPIOC->ODR ^= (1U << 13); //翻转PC13
        }
}
