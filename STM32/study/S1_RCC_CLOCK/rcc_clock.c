/* ============================================================================
 *  S1 — 时钟树与复位：搞清"我的芯片到底跑多快"
 * ============================================================================
 *  文件：firmware/study/S1_RCC_CLOCK/rcc_clock.c
 *
 *  为什么要做这个：
 *    你在 Lab1~Lab4 里反复踩过两类坑——
 *      ① "忘开时钟，引脚毫无反应"
 *      ② "频率算出来和实际对不上"
 *    这两类的根都在时钟树。做完这个模块，你应该能自己回答：
 *      · 我的 SYSCLK 是多少？从哪来的（HSI 还是 HSE 经 PLL）？
 *      · HCLK / PCLK1 / PCLK2 各是多少？
 *      · **TIM2 的计数时钟到底是多少？**（注意：不是 PCLK1！）
 *
 *  ---------------------------------------------------------------------------
 *  【背景知识 —— 先自己推一遍，再看下面】
 *
 *    STM32F103 的时钟链路：
 *
 *      HSI(8MHz 内部RC) ─┐
 *      HSE(外部晶振)    ─┴─▶ PLLSRC ─▶ PLL(×PLLMUL) ─▶ SYSCLK
 *                                                        │
 *                                                   AHB 预分频(HPRE) ─▶ HCLK
 *                                                        │
 *                                        ┌───────────────┴───────────────┐
 *                                   APB1 预分频(PPRE1)              APB2 预分频(PPRE2)
 *                                        │                               │
 *                                    PCLK1 (≤36MHz)                 PCLK2 (≤72MHz)
 *                                        │                               │
 *                              ★ 若 PPRE1 ≠ 1分频，挂在 APB1 上的
 *                                定时器时钟 = PCLK1 × 2 ★
 *
 *    本工程（72MHz 配置）的典型值：
 *      HSE=8MHz → PLL ×9 → SYSCLK=72MHz
 *      HPRE=1   → HCLK=72MHz
 *      PPRE2=1  → PCLK2=72MHz
 *      PPRE1=2  → PCLK1=36MHz   ★ 于是 TIM2/3/4 的计数时钟 = 36×2 = **72MHz**
 *
 *    ⚠ 这就是"为什么 PSC=0 时 TIM2 是 72MHz 而不是 36MHz"。
 *      你 Lab2/Lab4 里所有 f_cnt=72MHz 的算法，都是靠这一条成立的。
 *  ---------------------------------------------------------------------------
 *
 *  ===== 任务 =====
 *  T1：读出 RCC->CFGR，判断当前系统时钟源（SWS）与各路分频，
 *      手算出 SYSCLK / HCLK / PCLK1 / PCLK2 并写在下面。
 *  T2：用 TIM2 产生 **1Hz** 方波（PC13 的 LED 每秒闪一次）。
 *      分别用两组假设算 PSC/ARR：
 *        甲组：以为 f_cnt = PCLK1 = 36MHz
 *        乙组：以为 f_cnt = PCLK1×2 = 72MHz
 *      下载观察哪一组真的是 1Hz → 用实验证明"定时器时钟×2"。
 *  T3：故意复现你踩过的坑：先配 GPIOA 引脚、但**不开** GPIOA 时钟，
 *      看 LED 是否还闪（并想一想：为什么"不报错、但没反应"？）
 *
 *  ===== 涉及寄存器 =====
 *    RCC->CR      HSIRDY / HSERDY / PLLRDY（时钟是否就绪）
 *    RCC->CFGR    SWS[3:2] 系统时钟源；HPRE[7:4]；PPRE1[10:8]；PPRE2[13:11]；PLLMUL[21:18]
 *    RCC->APB2ENR / APB1ENR   外设时钟门控
 *
 *  ===== 思考题 =====
 *  Q1：为什么 STM32 要"每个外设一个时钟开关"，而 8051 不用？
 *      （提示：功耗——关掉不用的外设能省多少？）
 *  Q2：如果把 PCLK1 设成不分频（=72MHz），会怎样？（查手册的 APB1 上限）
 *  Q3：你 Lab4 里 PSC=0、ARR=287 得到 4µs。若有人把 PPRE1 改成 1 分频
 *      （PCLK1=72MHz，超出规格仅作思想实验），TIM2 的计数时钟会变成多少？
 *      4µs 还成立吗？
 * ========================================================================== */

