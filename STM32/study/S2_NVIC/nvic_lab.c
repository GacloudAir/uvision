/* ============================================================================
 *  S2 — 中断与 NVIC：为什么我的 ISR 会"晚"？
 * ============================================================================
 *  文件：firmware/study/S2_NVIC/nvic_lab.c
 *
 *  为什么要做这个：
 *    Lab4 路线 B 里你用了中断，但有几个问题当时没深究：
 *      · 为什么边沿会**整体晚约 0.3µs**？
 *      · 两个中断同时来，谁先执行？
 *      · 一个中断正在执行时，另一个能"插队"吗？
 *    本模块用两个可观察的实验把这三件事讲清楚。
 *
 *  ---------------------------------------------------------------------------
 *  【关键概念】
 *
 *    1) 中断延迟的构成（从"事件发生"到"ISR 第一条语句执行"）：
 *         硬件响应(约 12 个周期) + 入栈 + 取向量  ≈ 0.15~0.2 µs @72MHz
 *       再加上你 ISR 里第一条有效语句之前的时间 → 合计约 0.3µs。
 *       ★ 这就是为什么 Lab4 路线 B 的四条边沿会整体晚，
 *         但因为**每次都一样晚**，所以相对关系（图 6 的那些"同时"）仍然正确。
 *
 *    2) 优先级：抢占(preemption) vs 子优先级(subpriority)
 *       - 抢占优先级高的中断，可以**打断**正在执行的低优先级 ISR
 *       - 抢占优先级相同 → 子优先级高的先排队，但**不能互相打断**
 *       - 在 F103（4 位优先级）上，分组由 NVIC_SetPriorityGrouping() 决定：
 *           抢占位数 = 7 − PRIGROUP
 *           本 Lab 用 NVIC_SetPriorityGrouping(3) → 4 位抢占、0 位子优先级
 *
 *    3) ISR 名字必须和启动文件里的向量名一致，否则会进 Default_Handler（死循环）
 *  ---------------------------------------------------------------------------
 *
 *  ===== 实验设计 =====
 *    · TIM3：每 500ms 产生一次更新中断，优先级**低(5)**
 *            ISR 里**故意忙等约 300ms**（人为制造一个长中断）
 *            ISR 开始/结束时翻转 PA1，方便示波器看 ISR 的"宽度"
 *    · EXTI0（PA0 按键，下降沿）：优先级**高(0)**
 *            ISR 里点亮 PC13 的 LED
 *
 *    操作与观察：
 *      ① 只跑 TIM3：示波器 PA1 上看到 300ms 宽的高电平，每 500ms 一次
 *      ② 在 TIM3 的长中断**期间**按下 PA0 按键：
 *         若 LED **立刻亮** → 抢占成功（高优先级打断了低优先级）
 *         若 LED 要等 TIM3 的 ISR 跑完才亮 → 抢占没生效，检查优先级设置
 *      ③ 把两者优先级对调，再试一次 → 对比
 *
 *  ===== 涉及寄存器 =====
 *    RCC->APB2ENR   AFIOEN(bit0) ★ 配 EXTI 时必须开 AFIO 时钟！
 *    AFIO->EXTICR[0]            选择 EXTI0 来自哪个端口（0000=PA, 0001=PB...）
 *    EXTI->IMR / FTSR / RTSR    中断屏蔽 / 下降沿 / 上升沿
 *    EXTI->PR                   挂起标志（**写 1 清除**）
 *    NVIC                       优先级分组 + SetPriority + EnableIRQ
 *
 *  ===== 思考题 =====
 *  Q1：为什么 EXTI 要开 AFIO 时钟？不开会怎样？
 *  Q2：如果两个中断抢占优先级相同，后到的那个会怎样？
 *  Q3：ISR 里做 printf / 浮点运算会有什么后果？对 Lab4 的波形意味着什么？
 *  Q4：怎么把 Lab4 的中断延迟从 0.3µs 降下来？（提示：ISR 越短越好 + 合并寄存器写）
 * ========================================================================== */

