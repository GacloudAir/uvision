/* ============================================================================
 *  L4 — TIM + DMA 搬 BSRR：零抖动边沿  ★ 计划层①低抖动（进阶） ★
 * ============================================================================
 *  文件：firmware/gen/L4_dma/lab4_dma.c
 *
 *  目标：
 *    用 DMA 把"预先算好的 BSRR 字"在定时器每个更新事件自动搬进 GPIOx->BSRR，
 *    让引脚电平随硬件节拍翻转，**完全不经过中断/CPU**。
 *    这样边沿抖动从"中断延迟 ≈0.3µs"降到"仅取决于定时器时钟"（≈13.9ns 量化步长）。
 *
 *  为什么要做这个（计划层①"低抖动"）：
 *    L1 阶段 B 用中断在 tick 0/72/144 翻 GPIO，ISR 本身有 ≈0.3µs 延迟，
 *    相对 4µs 周期是 7.5% 的抖动。对"精密时序"这是硬伤。
 *    DMA 把翻转动作从"软件"挪到"硬件自动搬运"，CPU 不参与，抖动消失。
 *
 *  ★ 原理（核心）★
 *    把要输出的波形，按最小时间量子（1 tick）拆成一张表 bsfr_buf[]：
 *        bsfr_buf[i] = 第 i 个 tick 时，应该写进 GPIOA->BSRR 的值
 *                     （置位某脚 = 1<<pin；复位某脚 = 1<<(pin+16)）
 *    定时器每数 1 个 tick 产生一次"更新事件"，触发一次 DMA：
 *        把 bsfr_buf[next] 搬到 GPIOA->BSRR（一次 store，引脚即变）
 *    DMA 配成"循环模式"→ 表播完自动从头播 → 波形持续输出，CPU 全程闲置。
 *
 *  硬件事实（STM32F103）：
 *    - TIM2 的"更新"是 DMA1 的硬件请求，映射到 DMA1_Channel2
 *    - GPIOx->BSRR 是 32 位寄存器（低 16 位置位、高 16 位复位）
 *    - DMA 外设地址固定 &GPIOA->BSRR；内存地址在 bsfr_buf 上自增；
 *      数据宽度 32 位；循环模式(CIRC)让波形自动重复
 *
 *  你会用到的寄存器：
 *    RCC->AHBENR     DMA1EN(bit0)
 *    DMA1_Channel2->CPAR   外设地址 = &GPIOA->BSRR
 *    DMA1_Channel2->CMAR   内存地址 = bsfr_buf
 *    DMA1_Channel2->CNDTR  传输次数 = 表长
 *    DMA1_Channel2->CCR    EN/MINC/CIRC/MSIZE=2/PSIZE=2/PL
 *    TIM2->DIER     UDE(bit8) 使能"更新"触发 DMA（不是 UIE 中断！）
 *    TIM2->PSC/ARR/CR1      时基与启动（ARR=1 即每 tick 一次更新）
 *
 *  ===== 思考题 =====
 *  Q1：为什么用 BSRR 而不是 ODR？DMA 搬 ODR 会把"没在动的脚"也冲掉吗？
 *  Q2：表长 = 周期 tick 数（如 288）。若想输出 10ms 周期，表要多长？内存够吗？
 *  Q3：DMA 是"循环模式"，那波形怎么停下来？（提示：关 TIM2 的 CEN 或 DMA 的 EN）
 *  Q4：这种"表驱动"方式，改频率要怎么做？（提示：重算整张表并重载 CNDTR）
 * ========================================================================== */

