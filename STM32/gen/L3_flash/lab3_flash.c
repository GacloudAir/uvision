/* ============================================================================
 *  L3 — 参数存 Flash + 上电恢复 + IWDG 看门狗 + 合法性校验  ★ 计划层①持久化 ★
 * ============================================================================
 *  文件：firmware/gen/L3_flash/lab3_flash.c
 *
 *  目标：
 *    把"时序参数"（频率、各通道脉宽/相位、运行标志）存进 STM32 内部 Flash
 *    的最后一页；上电自动读回；同时挂一个独立看门狗(IWDG)，程序卡死就复位；
 *    读回的参数要做范围校验 + 结构体校验，超范围直接拒绝、回落到默认值。
 *
 *  为什么要做这个：
 *    计划要求"断电重上电参数不丢"。RAM 掉电即失，Flash 不掉；
 *    但 Flash 写很慢、有寿命（≈1万次）、必须按 16 位对齐写、写前要先擦页。
 *    看门狗保证"即使协议/时序逻辑跑飞，板子也能自己起来"。
 *
 *  硬件事实（STM32F103C8T6，中等容量）：
 *    - Flash 共 64KB，按 1KB/页 划分，共 64 页（页号 0..63）
 *    - 末页地址 = 0x0800FC00（页 63），我们就把参数存在这一页
 *    - Flash 写单位 = 16 位（半字）；写前必须擦除整页（擦后全 0xFFFF）
 *    - Flash 解锁钥匙：KEYR 依次写 0x45670123、0xCDEF89AB
 *
 *  你会用到的寄存器：
 *    FLASH->KEYR   解锁（两次写密钥）
 *    FLASH->CR      LOCK / PER(页擦) / STRT(开始擦) / PG(编程) / BSY(忙)
 *    FLASH->AR      要擦的页地址（PER=1 时）
 *    FLASH->SR      EOP(操作完成) / BSY(忙)
 *    IWDG->KR      0x5555=允许改寄存器, 0xAAAA=喂狗, 0xCCCC=启动看门狗
 *    IWDG->PR / RLR 预分频 / 重载值（决定超时，如 0x0FFF ≈ 数秒）
 *
 *  ===== 思考题 =====
 *  Q1：为什么"写前必须整页擦除"？能不能只改一个字节？（提示：Flash 只能把 1 写 0）
 *  Q2：参数结构体里为什么要放一个"校验和/CRC"？只做范围校验不够吗？
 *  Q3：IWDG 是"独立"看门狗——主频崩了它还能跑吗？这和窗口看门狗 WWDG 有何不同？
 *  Q4：如果参数页全是 0xFFFF（从没写过），读回后该怎么处理？
 * ========================================================================== */

