/* ---------------------------------------------------------------------------
 *  【核心难点】为什么 CH4 的"中间窗口"做不出？
 *    一个定时器只有一条 CNT，PWM 窗口只能贴"起点"(PWM1) 或"终点"(PWM2)：
 *      PWM1（110）→ 高电平 [0, CCR)
 *      PWM2（111）→ 高电平 [CCR, ARR+1)
 *    CH1/CH2/CH3 都从 0 开始 → PWM1 搞定；
 *    CH4 = [72,144) 夹在正中间，两种模式都做不出 → 必须换一个相位。
 *  解决（路线 B，最朴素可靠）：用第二个定时器 TIM3 专门产 CH4，
 *    把 TIM3 的 CNT 预置成 (周期 − 72) = 216，再启动。两个定时器同频同源，
 *    启动后相位永久保持；残余误差只有"两条启动指令之间几个周期"（≈0.1µs）。
 *    （注意：用"主从触发复位 SMS=100"对齐长电平窗口会翻车——触发占空比高时
 *     把从定时器 CNT 按住贴 0，输出恒高直线。预置 CNT 更稳。）
 * ------------------------------------------------------------------------- */

