/* ============================================================================
 *  L1 — 多通道精密时序：从单通道可变脉宽到多通道相位对齐  ★ 项目核心 ★
 * ============================================================================
 *  文件：firmware/gen/L1_timing/lab1_timing.c
 *
 *  目标（分两阶段，对应计划里程碑 W1 → W2）：
 *    阶段 A（W1）：用 TIM2_CH1 在 PA0 输出"占空比/周期可调"的方波，
 *                  由几个宏决定参数，编译后示波器能看到变化。
 *    阶段 B（W2）：扩成 4 路输出（PA0..PA3），彼此可以同相，也可以
 *                  设定固定的相位偏移；其中至少有一路是"夹在周期中间"的
 *                  高电平窗口（下面会解释为什么这路最难）。
 *
 *  为什么要做这个：
 *    计划的全部价值都建立在"能产生多路精确时序"上。先把它做对，
 *    后面的协议、自检才有东西可下发、可测量。
 *
 *  建议默认参数（方便和示波器对照，也是本项目常用值）：
 *    f_cnt = 72MHz（PSC = 0，不分频）→ 1 tick = 13.9ns
 *    f_out = 250kHz → ARR = 287（288 tick = 4µs）
 *    改频率 = 保持 f_cnt=72MHz，按比例改 ARR 与各 CCR（不要动 PSC）。
 *
 *  涉及知识（见 docs/学习路线图.md 模块 2、3）：
 *    定时器时基（PSC/ARR/CNT）、PWM 模式 1/2、输出比较、复用引脚、
 *    多通道相位（同 TIM 多 CCR / 跨定时器预置 CNT）。
 *
 *  你会用到的寄存器：
 *    RCC->APB1ENR   TIM2EN(bit0) / TIM3EN(bit1)
 *    RCC->APB2ENR   IOPAEN(bit2)              ★ GPIO 时钟！漏了引脚没波形
 *    TIMx->PSC / ARR            时基（周期）
 *    TIMx->CCMR1 / CCMR2        通道模式（PWM1=110 / PWM2=111 / 冻结=000）
 *    TIMx->CCR1..CCR4           各通道比较值（决定占空比/相位）
 *    TIMx->CCER                 CC1E..CC4E 输出使能
 *    TIMx->CR1                  CEN 启动计数器
 *    TIMx->CNT                  计数器当前值（跨定时器相位用"预置"它）
 *    GPIOA->CRL                 配 PA0..PA7（复用推挽 = 0xB）
 *
 *  核心公式（先自己推一遍）：
 *    f_cnt = 72MHz / (PSC+1)
 *    f_out = f_cnt / (ARR+1)
 *    占空比 = CCR / (ARR+1)         （PWM1：CNT<CCR 期间为高）
 *
 *  ===== 思考题（务必先算再写） =====
 *  Q1：250kHz 需要 (PSC+1)*(ARR+1)=288。为"分辨率最高"，PSC 取 0 时 ARR 是多少？
 *  Q2：占空比 25% / 50% 时 CCR 分别等于多少（ARR=287）？
 *  Q3：想让 CH2 比 CH1"滞后 1/4 周期"，只要把 CH2 的 CCR 加 (ARR+1)/4 吗？
 *      这能做出"贴起点"的窗口，但做不出"夹在中间"的窗口——为什么？见下方【核心难点】。
 * ========================================================================== */

