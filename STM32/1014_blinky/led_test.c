#include "stm32f10x.h"

/* ============================================================================
 *  最小 LED 测试（诊断用）
 * ----------------------------------------------------------------------------
 *  这个程序只做一件事：让板载 LED（PC13）以约 1Hz 闪烁。
 *  它**不涉及**定时器、不涉及 PA0、不涉及任何复杂逻辑。
 *
 *  用法：把本文件设为工程要编译的那个（或临时替换 lab2_pwm.c 的内容），
 *        下载后看 LED 会不会闪。
 *
 *  判读：
 *    ✔ LED 会闪  → 硬件、LED 极性、下载链路都正常，
 *                   那么问题在 Lab2 的程序逻辑里。
 *    ✘ LED 不闪  → 问题在硬件/下载，先解决这个（换极性试试、查接线）。
 *
 *  若闪烁速度太快或太慢，调整下面的 LOOP_COUNT。
 * ========================================================================== */

#define LOOP_COUNT   1000000UL

int main(void)
{
    /* 1) 开 GPIOC 时钟 */
    RCC->APB2ENR |= (1U << 4);

    /* 2) 配 PC13 为通用推挽输出（PC13 在 CRH，起始位 = (13-8)*4 = 20） */
    GPIOC->CRH &= ~(0xF << 20);
    GPIOC->CRH |=  (0x3 << 20);

    /* 3) 无限翻转 */
    while (1)
    {
        GPIOC->ODR ^= (1U << 13);       /* 翻转 PC13 */
        for (volatile uint32_t i = 0; i < LOOP_COUNT; i++)
        {
            /* 空转延时 */
        }
    }
}
