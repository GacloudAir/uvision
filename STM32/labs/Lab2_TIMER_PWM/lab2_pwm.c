#include "stm32f10x.h"

/* ===========================================================================
 *  【新增】让板载 LED（PC13）跟随 PA0 —— 没有示波器时的"人肉示波器"
 * ===========================================================================
 *  思路：PA0 由定时器产生波形（悬空时你什么也看不见），
 *        主循环不断读 PA0 的**实际电平**，把它"搬"到 PC13 的板载 LED 上。
 *        低频时（如 2Hz）LED 就会跟着 PA0 一起亮灭。
 *
 *  原理：即使 PA0 配成了"复用输出"，`IDR` 仍然能读回引脚的**真实电平**
 *        —— 输入通路一直有效，与输出配置无关。
 *
 *  ⚠️ 板载 LED 极性：多数 STM32 蓝板是**低电平点亮**
 *      （接法：3.3V → 电阻 → LED → PC13）。
 *      若你的板子是"高电平点亮"，把下面的 1U 改成 0U 即可。
 * =========================================================================== */
#define LED_ACTIVE_LOW   1U

static void led_init(void)
{
    /* 1) 开 GPIOC 时钟（APB2 的 bit4 = IOPCEN） */
    RCC->APB2ENR |= (1U << 4);

    /* 2) 配 PC13 为通用推挽输出 50MHz
     *    PC13 在 CRH 寄存器里，起始位 = (13 - 8) × 4 = 20 */
    GPIOC->CRH &= ~(0xF << 20);
    GPIOC->CRH |=  (0x3 << 20);

    /* 3) 初始状态：先让 LED 熄灭 */
#if LED_ACTIVE_LOW
    GPIOC->BSRR = (1U << 13);   /* 低电平点亮 → 输出高 = 灭 */
#else
    GPIOC->BRR  = (1U << 13);   /* 高电平点亮 → 输出低 = 灭 */
#endif
}

/* ---------------------------------------------------------------------------
 *  timer_pwm_init：配置 TIM2_CH1 在 PA0 输出方波
 *    psc, arr : 时基参数（由你在 main 里算好后传入）
 *    ccr      : 占空比比较值
 * ------------------------------------------------------------------------- */
static void timer_pwm_init(uint16_t psc, uint16_t arr, uint16_t ccr)
{
    /* ===== TODO 2-1：使能 TIM2 的时钟 =====
     * 提示：TIM2 在 APB1 总线上，别写成 APB2。
     * ★ 同时别忘了开 **GPIOA 的时钟**（它在 APB2）——
     *   漏了这一步，下面 TODO 2-2 里对 GPIOA->CRL 的写入会全部无效，
     *   PA0 停在默认的浮空输入，什么波形都不会有。（这是本项目第一坑！）
     */
    /* 你的代码： */
    RCC->APB1ENR |= (1U << 0);//这里为什么要强调1U(unsigned)而不直接写1？
    /* ↑【回答】1U 表示"无符号的 1"，有三个好处：
     *   1) 安全：1<<31 若 1 是有符号 int，等于把符号位置 1，
     *      在 C 标准里是"未定义行为"；而 1U<<31 明确就是 0x80000000。
     *   2) 类型匹配：寄存器都是 uint32_t（无符号），
     *      用无符号常量可避免有/无符号混算的警告。
     *   3) 可移植：某些编译器 int 只有 16 位，1<<16 会溢出丢失；
     *      写 1U<<24 这种大移位时才不会慌。
     *   在 STM32 上 int 就是 32 位，写 1<<0 也能跑；
     *   但请养成习惯——**移位超过 16 位，一律加 U**。
     */

    /* ===== TODO 2-2：把 PA0 配置为"复用推挽输出" =====
     * 提示：普通推挽 CNF=00，复用推挽 CNF=10（MODE 仍可选 11 高速）。
     *       想一想：为什么这里必须用"复用"而不是"普通推挽"？
     *       （提示：输出信号现在由定时器产生，不再由 ODR 控制）
     */
    /* 你的代码： */
    GPIOA->CRL &= ~0xF;//使用&+~安全清零
    GPIOA->CRL |= 0xB;
    /* ↑【BUG-1】移位错了！0xB000 把 0xB 放到了 bit15:12，那是 PA3 的位置。
     *   PA0（TIM2_CH1）在 CRL 的 bit3:0，应该写：
     *       GPIOA->CRL |= 0xB;             // 或 (0xB << 0)
     *   现在的写法导致：PA3 被配成复用推挽，而 PA0 什么都没配（还是输入模式）
     *   → 定时器再怎么输出，PA0 上也不会有波形。
     *   （这也是"值 << POS"没做对的典型例子，见 docs/GPIO配置与引脚速查.md）
     */

    /* ===== TODO 2-3：设置 PSC 和 ARR =====
     * 提示：直接用参数赋值即可；思考题 Q1/Q3 算出的是它们的值。
     *       有些系列需要写"预装载寄存器"(PSC/ARR 在更新事件后生效)，
     *       这里先用最简单的直接赋值，后面再深入。
     */
    /* 你的代码： */
    TIM2->PSC = psc;//分频系数
    TIM2->ARR = arr;//计数次数
    //为了方便观察，设定0.5秒(计时器计数36M次)
    /* ↑【BUG-2】PSC / ARR 是"寄存器名"，不是变量名——你这里等于在给
     *   一个不存在的变量赋值，编译器直接报 "undeclared identifier"。
     *   应该写成：
     *       TIM2->PSC = 5999;
     *       TIM2->ARR = 5999;
     *   顺带一提：函数参数 psc/arr/ccr 传进来你也没用，
     *   所以编译器还报了 3 个 unused parameter 警告。
     *   要么用参数，要么干脆不传参数——两种风格选一种，别混。
     */

    /* ===== TODO 2-4：把通道 1 配成 PWM 模式 1 =====
     * 提示：CCMR1 的 OC1M 位域 = 110 表示 PWM 模式 1；
     *       同时建议置位 OC1PE（输出比较预装载使能），改 CCR 时更平滑。
     */
    /* 你的代码： */
    TIM2->CCMR1 &= ~((0x7 << 4) | (0x1 << 3));
    TIM2->CCMR1 |= (0x6 << 4) | (0x1 << 3);
    /* ↑【BUG-3】两处问题：
     *   (a) 你在前面开的是 TIM2 的时钟（RCC->APB1ENR 的 bit0 = TIM2EN），
     *       但这里操作的是 TIM1 —— TIM1 挂在 APB2，要开
     *       RCC->APB2ENR 的 bit11（TIM1EN）。时钟没开，写 TIM1 全无效。
     *       → 建议：把上面几处 TIM1 都改回 TIM2，跟讲义和后续 Lab3/Lab4 一致。
     *
     *   (b) 运算符优先级陷阱：~(0x7 << 4) | (0x1 << 3)
     *       因为 ~ 的优先级比 | 高，实际算成了
     *         ((~(0x7<<4)) | (0x1<<3)) = 0xFFFFFF8F | 0x08 = 0xFFFFFF8F
     *       结果"碰巧"也清掉了 bit6:4 和 bit3，所以功能上没错。
     *       但这是运气，不是设计。规范写法是加括号：
     *         TIM2->CCMR1 &= ~((0x7U << 4) | (0x1U << 3));
     */

    /* ===== TODO 2-5：设置比较值 CCR1（决定占空比） ===== */
    /* 你的代码： */
    TIM2->CCR1 = ccr;  //ARR+1=6000,取3000得到50%占空比
    /* ↑【漏改】这里是 TIM1->CCR1，其他 TIM2 都改好了，唯独这条漏了。
     *   TIM1 没开时钟，写它不生效，所以 CCR1 实际没写进去 → 占空比不会是 50%。
     */
    /* （顺带：你的参数选择是对的。PSC=5999 → 72M/6000 = 12kHz；
     *  ARR=5999 → 12k/6000 = 2Hz，正好 0.5 秒一亮一灭，方便肉眼看 LED。
     *  CCR1=3000 → 3000/6000 = 50% 占空比。✓
     *  讲义允许"没示波器就把频率降下来用 LED 观察"，你这个思路是对的。） */


    /* ===== TODO 2-6：使能通道 1 输出 =====
     * 提示：CCER 的 CC1E 位。
     */
    /* 你的代码： */
    TIM2->CCER |= (1U << 0);  //使能通道1输出（CCER 的 CC1E）
    /* ↑【修正】你把寄存器名打成了 ER1（编译报 no member named 'ER1'）。
     *   另外：这一行在 TODO 2-6 的位置，本意是"使能通道输出"，
     *   对应的寄存器是 CCER（bit0 = CC1E），不是 CR1。
     *   缺了 CC1E，定时器虽然在数，但 PA0 上不会有波形。
     */
    /* ↑【BUG-4】这行其实是"启动计数器"（CR1 的 bit0 = CEN），
     *   但 TODO 2-6 要的是"使能通道输出"—— CCER 的 CC1E（bit0）。
     *   没有 CC1E，定时器虽然在数，但引脚上没有波形输出！
     *   应补：  TIM2->CCER |= (1U << 0);
     *   注意：TIM1/TIM2 的 CCER 里 TIM1 还有 CC1P（极性）、CC1NP（互补输出）
     *   等位，STM32F103 的 TIM1 是高级定时器，配置比 TIM2 多，这也是
     *   建议你用 TIM2 的原因之一——本项目用不到死区/互补输出。
     */


    /* ===== TODO 2-7：启动计数器 =====
     * 提示：CR1 的 CEN 位。不开它，定时器纹丝不动。
     */
    /* 你的代码： */
    TIM2->CR1 |= (1U << 0);
    /* ↑【BUG-5】TIM1 没有名为 CEN 的寄存器成员（CEN 是 CR1 里的 bit0，
     *   不是独立寄存器）。编译器直接报 "no member named 'CEN' in 'TIM_TypeDef'"。
     *   正确写法：  TIM2->CR1 |= (1U << 0);   // 即上面 TODO 2-6 那行做的事
     *   而且注意：上面 TODO 2-6 已经写过一次 CR1 CEN 了，这里就重复了。
     *   实际只需一次：开通道输出（CCER） + 启动计数（CR1 CEN），两步都要。
     */
}

int main(void)
{
    /* ===== 阶段 A：先试 1 kHz =====
     * 请先用思考题 Q3 的结论算出 PSC / ARR，并想好占空比对应的 CCR。
     * 把下面三个数字改成你算出来的值（不要照抄示例）：
     *     timer_pwm_init( ____ , ____ , ____ );
     *
     * 验证：示波器看到 1kHz、约 50% 的方波；若没有示波器，
     *       可以把频率降到几 Hz，用 LED 看它闪烁。
     */
    led_init();                         /* 【新增】把板载 LED(PC13) 配成输出 */
    timer_pwm_init(5999, 5999, 3000);   /* 2Hz、50% —— 低频，肉眼可见 */
    /* ↑【BUG-6】PSC / ARR / CCR 都不是定义过的宏或变量，编译器报
     *   "undeclared identifier" × 3。
     *   这里应该直接写字面量（你自己算出来的数）：
     *       timer_pwm_init(5999, 5999, 3000);
     *   或者先在文件顶部 #define：
     *       #define PSC_VAL 5999
     *       #define ARR_VAL 5999
     *       #define CCR_VAL 3000
     *       ...
     *       timer_pwm_init(PSC_VAL, ARR_VAL, CCR_VAL);
     *   （顺带：PSC/ARR 是寄存器名，把它们当变量名用容易和寄存器搞混，
     *     命名时建议加个后缀，如 PSC_VAL。）
     */

    /* ===== 阶段 B：改成 250 kHz =====
     * 想清楚 288 怎么分解（Q1），再把下面这行的注释打开，
     * 同时把上面那行注释掉：
     *     timer_pwm_init( ____ , ____ , ____ );
     */

    while (1)
    {
        /* ===== 【新增】把 PA0 的电平"复制"到 PC13 的板载 LED =====
         *   PA0 高 → LED 亮
         *   PA0 低 → LED 灭
         *
         * 主循环跑得足够快，所以低频（如 2Hz）时 LED 会跟着 PA0 一起闪。
         * ⚠️ 250kHz 时主循环跟不上，LED 会一直亮 —— 这招只适合低频验证。
         */
        if (GPIOA->IDR & (1U << 0))
        {
            /* PA0 = 高 → 点亮 LED */
#if LED_ACTIVE_LOW
            GPIOC->BRR  = (1U << 13);   /* 低电平点亮：拉低 */
#else
            GPIOC->BSRR = (1U << 13);   /* 高电平点亮：拉高 */
#endif
        }
        else
        {
            /* PA0 = 低 → 熄灭 LED */
#if LED_ACTIVE_LOW
            GPIOC->BSRR = (1U << 13);   /* 低电平点亮：拉高 */
#else
            GPIOC->BRR  = (1U << 13);   /* 高电平点亮：拉低 */
#endif
        }
    }
}

