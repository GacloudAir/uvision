#include <C8051F350.h>  // 包含C8051F350的寄存器定义

// 简单的延时函数
void delay(unsigned int count) {
    while(count--);
}

void main(void) {
    // 1. 关闭看门狗定时器（C8051F350复位后看门狗是默认开启的，必须关闭）
    WDTCN = 0xDE;
    WDTCN = 0xAD;

    // 2. 配置P0.0为推挽输出模式
    // 先确保P0.0被配置为数字输入（默认就是，但显式设置更稳妥）
    P0MDIN |= 0x01;   // 设置P0.0为数字输入
    P0MDOUT |= 0x01;  // 设置P0.0为推挽输出
    P0SKIP |= 0x01;   // 让交叉开关跳过P0.0，使其作为普通GPIO使用

    // 3. 使能交叉开关（必须使能，否则端口输出驱动器不工作）
    XBR1 = 0x40; // 0x40 是 XBARE 位，使能交叉开关

    // 4. 主循环
    while (1) {
        P0 &= ~0x01;  // P0.0 输出低电平，点亮LED
        delay(50000); // 延时
        P0 |= 0x01;   // P0.0 输出高电平，熄灭LED
        delay(50000); // 延时
    }
}